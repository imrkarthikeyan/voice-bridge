CREATE TABLE audience_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_id BIGINT NOT NULL UNIQUE,
    display_name VARCHAR(120),
    photo_url VARCHAR(255),
    headline VARCHAR(300),
    bio VARCHAR(2000),
    skills VARCHAR(1000),
    interests VARCHAR(1000),
    github_url VARCHAR(500),
    linkedin_url VARCHAR(500),
    portfolio_url VARCHAR(500),
    github_verified BOOLEAN NOT NULL DEFAULT FALSE,
    photo_visibility VARCHAR(20) NOT NULL DEFAULT 'NONE',
    bio_visibility VARCHAR(20) NOT NULL DEFAULT 'NONE',
    skills_visibility VARCHAR(20) NOT NULL DEFAULT 'NONE',
    links_visibility VARCHAR(20) NOT NULL DEFAULT 'NONE',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_audience_profile_participant FOREIGN KEY (participant_id) REFERENCES participants(id)
);
