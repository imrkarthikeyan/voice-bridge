CREATE TABLE meeting_settings (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id           BIGINT NOT NULL,
    subtitles_enabled    BOOLEAN NOT NULL DEFAULT FALSE,
    audience_profiles_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    created_at           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_meeting_settings_meeting UNIQUE (meeting_id),
    CONSTRAINT fk_meeting_settings_meeting FOREIGN KEY (meeting_id) REFERENCES meetings (id)
);

CREATE TABLE ai_jobs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id     BIGINT,
    job_type       VARCHAR(60) NOT NULL,
    status         VARCHAR(20) NOT NULL,
    payload        TEXT,
    result         TEXT,
    error_message  VARCHAR(2000),
    created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at     TIMESTAMP NULL,
    completed_at   TIMESTAMP NULL,
    CONSTRAINT fk_ai_jobs_meeting FOREIGN KEY (meeting_id) REFERENCES meetings (id)
);

CREATE INDEX idx_ai_jobs_status_created_at ON ai_jobs (status, created_at);
CREATE INDEX idx_ai_jobs_meeting_id ON ai_jobs (meeting_id);

CREATE TABLE transcript_segments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id     BIGINT NOT NULL,
    segment_id     VARCHAR(80) NOT NULL,
    revision       INTEGER NOT NULL,
    source         VARCHAR(20),
    participant_id BIGINT,
    language       VARCHAR(16),
    text           VARCHAR(4000) NOT NULL,
    partial        BOOLEAN NOT NULL DEFAULT FALSE,
    start_ms       BIGINT,
    end_ms         BIGINT,
    confidence     DOUBLE PRECISION,
    created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_transcript_segments_meeting FOREIGN KEY (meeting_id) REFERENCES meetings (id)
);

CREATE INDEX idx_transcript_segments_meeting_created ON transcript_segments (meeting_id, created_at);
CREATE INDEX idx_transcript_segments_segment_revision ON transcript_segments (segment_id, revision);

CREATE TABLE transcript_translations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    segment_id      BIGINT NOT NULL,
    target_language  VARCHAR(16) NOT NULL,
    text            VARCHAR(4000) NOT NULL,
    model           VARCHAR(80),
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_translation_segment_language UNIQUE (segment_id, target_language),
    CONSTRAINT fk_transcript_translation_segment FOREIGN KEY (segment_id) REFERENCES transcript_segments (id)
);

CREATE TABLE slides (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    presentation_id BIGINT NOT NULL,
    slide_number INTEGER NOT NULL,
    title VARCHAR(500),
    extracted_text VARCHAR(20000) NOT NULL,
    concepts_json VARCHAR(10000) NOT NULL,
    has_code BOOLEAN NOT NULL DEFAULT FALSE,
    has_table BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_slides_presentation_number UNIQUE (presentation_id, slide_number),
    CONSTRAINT fk_slides_presentation FOREIGN KEY (presentation_id) REFERENCES presentations (id)
);

CREATE TABLE slide_visits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id BIGINT NOT NULL,
    presentation_id BIGINT NOT NULL,
    slide_number INTEGER NOT NULL,
    entered_ms BIGINT NOT NULL,
    left_ms BIGINT,
    entered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_slide_visits_meeting FOREIGN KEY (meeting_id) REFERENCES meetings (id),
    CONSTRAINT fk_slide_visits_presentation FOREIGN KEY (presentation_id) REFERENCES presentations (id)
);

CREATE TABLE questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id BIGINT NOT NULL,
    participant_id BIGINT NOT NULL,
    text VARCHAR(6000) NOT NULL,
    original_text VARCHAR(6000),
    type VARCHAR(32) NOT NULL,
    status VARCHAR(20) NOT NULL,
    slide_number INTEGER,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_questions_meeting FOREIGN KEY (meeting_id) REFERENCES meetings (id),
    CONSTRAINT fk_questions_participant FOREIGN KEY (participant_id) REFERENCES participants (id)
);

CREATE TABLE question_slide_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT NOT NULL,
    slide_id BIGINT NOT NULL,
    score DOUBLE PRECISION NOT NULL,
    CONSTRAINT uk_question_slide_link UNIQUE (question_id, slide_id),
    CONSTRAINT fk_question_slide_question FOREIGN KEY (question_id) REFERENCES questions (id),
    CONSTRAINT fk_question_slide_slide FOREIGN KEY (slide_id) REFERENCES slides (id)
);

CREATE TABLE timeline_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id BIGINT NOT NULL,
    type VARCHAR(30) NOT NULL,
    occurred_ms BIGINT NOT NULL,
    slide_number INTEGER,
    title VARCHAR(300) NOT NULL,
    details VARCHAR(6000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_timeline_events_meeting FOREIGN KEY (meeting_id) REFERENCES meetings (id)
);
CREATE INDEX idx_slide_visits_meeting_time ON slide_visits (meeting_id, entered_ms);
CREATE INDEX idx_questions_meeting_created ON questions (meeting_id, created_at);
CREATE INDEX idx_timeline_meeting_time ON timeline_events (meeting_id, occurred_ms);
