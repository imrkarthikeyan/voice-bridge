CREATE TABLE audience_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(180) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    display_name VARCHAR(120) NOT NULL,
    github_subject VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE participant_account_links (
    participant_id BIGINT PRIMARY KEY,
    account_id BIGINT NOT NULL,
    linked_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_participant_account_participant FOREIGN KEY (participant_id) REFERENCES participants(id) ON DELETE CASCADE,
    CONSTRAINT fk_participant_account_account FOREIGN KEY (account_id) REFERENCES audience_accounts(id) ON DELETE CASCADE
);
ALTER TABLE audience_profiles ADD COLUMN share_mode VARCHAR(20) NOT NULL DEFAULT 'NONE';
CREATE INDEX idx_participant_account_account ON participant_account_links(account_id);

CREATE TABLE profile_share_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id BIGINT NOT NULL,
    participant_id BIGINT NOT NULL,
    account_id BIGINT,
    share_mode VARCHAR(20) NOT NULL,
    payload TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_profile_snapshot_meeting FOREIGN KEY (meeting_id) REFERENCES meetings(id) ON DELETE CASCADE,
    CONSTRAINT fk_profile_snapshot_participant FOREIGN KEY (participant_id) REFERENCES participants(id) ON DELETE CASCADE,
    CONSTRAINT fk_profile_snapshot_account FOREIGN KEY (account_id) REFERENCES audience_accounts(id) ON DELETE SET NULL
);
CREATE INDEX idx_profile_snapshot_meeting_participant ON profile_share_snapshots(meeting_id, participant_id);

CREATE TABLE audience_profile_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT,
    participant_id BIGINT,
    meeting_id BIGINT,
    action VARCHAR(40) NOT NULL,
    details TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_profile_audit_account FOREIGN KEY (account_id) REFERENCES audience_accounts(id) ON DELETE SET NULL
);
CREATE INDEX idx_profile_audit_created_at ON audience_profile_audit_logs(created_at);
